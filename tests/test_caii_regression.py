"""Public regression checks on the bundled CA II export."""

from pathlib import Path

import numpy as np
import pandas as pd
import pytest

from chemgridmap import annotate_activity_confidence, curate_chembl_activity_data
from chemgridmap.app import AppSession, DEMO
from chemgridmap.columns import describe


@pytest.fixture(scope="module")
def caii_runs(tmp_path_factory):
    runs = {}
    for projection in ("umap", "pca"):
        session = AppSession(tmp_path_factory.mktemp(projection))
        session.load(DEMO.read_bytes(), DEMO.name)
        session.start(
            {
                "target_id": "CHEMBL205",
                "projection": projection,
                "output_formats": ["svg"],
                "grouping": "butina",
                "render_detail": "overview",
            },
            background=False,
        )
        assert session.job["state"] == "done", session.job
        runs[projection] = session
    return runs


def test_caii_default_reliability_values(caii_runs):
    data = caii_runs["umap"].result.data
    fit = caii_runs["umap"].curation.report["activity_confidence"]
    assert len(data) == 889
    assert data.class_status.eq("supported").sum() == 506
    assert ((data.class_status.eq("supported")) & data.activity_class.eq("active")).sum() == 390
    assert ((data.class_status.eq("supported")) & data.activity_class.eq("inactive")).sum() == 116
    assert data.offset_pair_touched.sum() == 0
    assert fit["sigma_doc"] == pytest.approx(0.796, abs=5e-4)
    assert fit["sigma_doc_degrees_of_freedom"] == 64
    assert fit["multi_unit_entry_count"] == 29
    assert fit["max_entry_id"] == "CHEMBL20"
    assert fit["max_entry_degrees_of_freedom_share"] == pytest.approx(26 / 64)
    assert fit["max_entry_sum_of_squares_share"] == pytest.approx(0.6308, abs=5e-4)
    assert fit["offset_display"] == "none"
    assert any("CHEMBL20" in warning for warning in fit["warnings"])
    offsets = pd.read_csv(caii_runs["umap"].files["map_document_offsets.csv"])
    assert len(offsets) == 4
    assert not offsets.systematic_offset.any()
    assert fit["document_offsets"] == []
    assert len(fit["document_pair_offsets"]) == 4
    assert np.nanmean(data.neighbor_recall) == pytest.approx(0.585, abs=0.02)
    assert np.nanmean(data.neighbor_recall_fixed_k) == pytest.approx(0.536, abs=0.02)


def test_caii_offset_display_settings_match_when_no_entry_is_touched():
    curated = curate_chembl_activity_data(
        pd.read_csv(DEMO), target_id="CHEMBL205", activity_type="IC50"
    )
    document_column = curated.report["detected_columns"]["document_id"]
    runs = {}
    for setting in ("none", "uncertain"):
        molecules, fit = annotate_activity_confidence(
            curated.molecules,
            curated.retained_records,
            value="activity_pchembl_raw",
            document=document_column,
            offset_display=setting,
        )
        runs[setting] = (molecules, fit)

    first, first_fit = runs["none"]
    second, second_fit = runs["uncertain"]
    assert first_fit["offset_display"] == "none"
    assert second_fit["offset_display"] == "uncertain"
    assert first.offset_pair_touched.sum() == 0
    assert second.offset_pair_touched.sum() == 0
    pd.testing.assert_series_equal(first.class_confidence, second.class_confidence)
    pd.testing.assert_series_equal(first.class_status, second.class_status)
    assert first.class_status.eq("supported").sum() == 506
    assert second.class_status.eq("supported").sum() == 506


def test_caii_pca_projection_coordinates_match_seed42_expectation(caii_runs):
    """Compare raw PCA coordinates with a table generated by this codebase.

    The table is generated from the bundled DEMO using target CHEMBL205, PCA,
    Butina grouping, overview rendering, and random_state 42 (the default).
    The default randomized SVD can differ by about 1e-4 across platforms;
    coordinates span approximately ±4, so use an absolute tolerance of 5e-4.
    """
    expected_path = Path(__file__).with_name("data") / "caii_pca_seed42_projection.csv"
    expected = pd.read_csv(expected_path, encoding="utf-8")
    actual = pd.read_csv(
        caii_runs["pca"].result.output_files["coordinates"], encoding="utf-8"
    )
    assert actual.molecule_identity_key.is_unique
    assert set(actual.molecule_identity_key) == set(expected.molecule_identity_key)
    actual = actual.set_index("molecule_identity_key").loc[expected.molecule_identity_key]
    for column in ("projection_x_raw", "projection_y_raw"):
        correlation = np.corrcoef(actual[column], expected[column])[0, 1]
        sign = 1 if correlation >= 0 else -1
        np.testing.assert_allclose(actual[column] * sign, expected[column], atol=5e-4)


